"""Rebuild juniper-ml#2606's content on current main, keeping only the rename of the PERSON.

Why this exists
---------------
#2606 replays about 100 of main's commits over the owner's blind "owner -> Overtoad" substitution, and
its scripted conflict resolution damaged 389 files beyond the rename (see
``2026-11-23_rename_pr_damage_audit.py``). The owner ruled on 2026-11-23 to rebuild it on current main.
Nothing is taken from #2606's version of a file that main already has: each such file is re-derived from
MAIN's text, so main's newer content can never be reverted.

What it writes into WORKTREE (a clean checkout of main)
-------------------------------------------------------
- living files in scope: MAIN's text with every "owner"/"Owner" that means the person renamed and every
  technical one kept, decided per occurrence by ``repair_line`` in ``2026-11-23_overtoad_rename_repair.py``
  (scope: the files #2606 modified or renamed, plus files main added since #2606's base)
- records, pinned files, symlinks, non-UTF-8 files and the requirements domain (``TECHNICAL_DOMAINS``,
  where "owner" is the owning repo's field): never written, so they stay main's bytes
- #2606's new files (owner rulings 6 and 7, 2026-11-23):
  - ``util/ad-hoc`` scripts: the pre-rename text is reconstructed with the two-step inverse
    ("The Overtoad" -> "Owner", then "Overtoad" -> "owner"), then renamed person-only like a living file
  - ``util/conflicted_files.bash`` moves to ``util/ad-hoc/2026-11-21_conflicted_files.bash``;
    ``util/conflicted_files.txt`` is dropped
  - new handoff records: the two-step inverse, reported as a reconstruction. ``--original PATH=FILE``
    names an older version recovered from the transcripts: lines it shares are counted as verified, and
    where a line differs only in an owner token its text wins (the inverse turns "The owner" into "Owner")
- ``AGENTS.md``: ``**Last Updated**:`` set to ``--today``
- markdown: a same-file link to a heading the rename changed is pointed at the heading's new anchor
  (``#11-owner-decisions-...`` -> ``#11-the-overtoad-decisions-...``); the anchor fragment itself is
  technical, so the per-occurrence rename keeps it, and only this remap moves it

Every written living file is checked line for line: a changed line must equal MAIN's line with some of its
"owner"/"Owner" tokens replaced in place by "Overtoad"/"The Overtoad", and nothing else changed.

Usage
-----
    python3 2026-11-23_pr2606_rebuild.py --worktree WT --old-base 81b8eaf7 --old-head 0658e854
        --today YYYY-MM-DD [--original REPOPATH=FILE ...] [--apply] [--report out.tsv]
"""

