# and generated by it. The whole domain stays main's bytes (full regression run, 2026-11-23).
TECHNICAL_DOMAINS = ("notes/requirements/", "util/requirements_", "tests/test_requirements_")
# Files kept at main's bytes because editing them would block the merge: main's ruleset carries a code-scanning
# rule (CodeQL, security_alerts_threshold high_or_higher), and a PR this large makes CodeQL count every alert in
