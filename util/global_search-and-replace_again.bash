##########################################################################################################################################################################################################################################
# Define default search and replace terms
SEARCH_TARGET_DEFAULT="Owner "
REPLACE_TARGET_DEFAULT="The Overtoad "


##########################################################################################################################################################################################################################################
# Parse Input Params if provided
SEARCH_TARGET="${1:-${SEARCH_TARGET_DEFAULT}}"
REPLACE_TARGET="${2:-${REPLACE_TARGET_DEFAULT}}"


##########################################################################################################################################################################################################################################
# Define Environment Variables
APPLICATION_PREFIX="juniper"
# APPLICATION_REPO_SEARCH="${APPLICATION_PREFIX}-*"
APPLICATION_REPO_SEARCH="${APPLICATION_PREFIX}-ml"

PROJECT_DIR="${HOME}/Development/python/Juniper"

EXTENSION_LIST="md py yaml yml toml bash"


##########################################################################################################################################################################################################################################
# Setup Environment for Search and Replace
cd "${PROJECT_DIR}" || exit 1


##########################################################################################################################################################################################################################################
# Perform Search and Replace
for dir in ${APPLICATION_REPO_SEARCH}; do
    echo "Dir: ${dir}"

    for ext in ${EXTENSION_LIST}; do
        echo "Dir: ${dir}, Ext: ${ext}"

        for file in $(find "${dir}" | grep  "\.${ext}"); do
            echo "Dir: ${dir}, Ext: ${ext}, File: ${file}"

            sed -i "s/${SEARCH_TARGET}/${REPLACE_TARGET}/g" "${file}"
        done
    done
done
